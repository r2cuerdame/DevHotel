/**
 * Where the guest serves the Room command channel, and the secret that opens it.
 *
 * Both are per-boot facts, which is why they are asked for rather than stored:
 * the address comes from DHCP on the runtime's private NIC and the token is
 * regenerated by the guest, so a value cached from a previous boot would point
 * the Host at nothing — or, worse, at whatever now holds that address.
 */
export interface ManagedHyperVGuestChannel {
  owner: 'devhotel'
  state: 'ready'
  address: string
  port: number
  token: string
}

export interface ManagedHyperVGuestTransport {
  health(pipePath: string): Promise<ManagedHyperVGuestStatus>
  /**
   * Resolves once the guest has both an address and a token. Optional so a
   * health-only transport — the one #106 shipped, and every test double built
   * against it — stays valid.
   */
  channel?(pipePath: string): Promise<ManagedHyperVGuestChannel>
}

export interface ManagedHyperVRuntimeMarker {
  schemaVersion: 2
  owner: 'devhotel'
  backend: 'hyper-v'
  installId: string
  runtimeId: string
  runtimeVersion: string
  vmName: string
  vmId: string | null
  vmPath: string
  /** Owned, immutable copy of the pinned Alpine boot ISO. */
  isoPath: string
  /** Disposable FAT disk carrying the DevHotel apkovl overlay. */
  seedPath: string
  /** Persistent Room and runtime state; never rebuilt by a repair. */
  statePath: string
  pipePath: string
  /** SHA-256 of the pinned boot ISO. */
  baseImageDigest: string
  /** SHA-256 of the generated overlay, binding the guest identity payload. */
  overlayDigest: string
  /**
   * Whether this Host actually granted nested virtualization to the VM.
   *
   * Hyper-V refuses it on hosts that cannot nest, and the refusal is
   * survivable -- the runtime boots and serves Web Rooms without it. What is
   * not survivable is losing the answer: only a guest that was granted it can
   * run KVM-backed Android emulators, so a later feature has to read what this
   * Host decided rather than re-derive it. `null` is a marker written before
   * this was recorded, and means unknown rather than refused.
   */
  nestedVirtualization?: boolean | null
  status: 'provisioning' | 'stopped' | 'starting' | 'ready' | 'broken'
  createdAt: string
  updatedAt: string
  failure?: string
}

export interface ManagedHyperVRuntimeObservation {
  state: 'not-installed' | 'preparing' | 'stopped' | 'ready' | 'broken'
  runtimeId: string | null
  runtimeVersion: string | null
  daemonVersion: string | null
  baseImageDigest: string | null
  /** What this Host granted at creation. `null` means unrecorded, not refused. */
  nestedVirtualization: boolean | null
  detail: string
}

